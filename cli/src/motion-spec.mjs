/** The spec for an id, or the best keyword match for words (stems of 4+ letters match word starts). */
export function matchMotion({ intent, query = '' } = {}) {
  if (intent) return MOTION_SPECS.filter((s) => s.id === intent);
  const words = (value) => value.toLowerCase().split(/[^\p{L}\p{N}]+/u).filter(Boolean).join(' ');
  const text = ` ${words(query)} `;
  const has = (k) => text.includes(` ${words(k)}${k.length >= 4 ? '' : ' '}`);
  const scored = MOTION_SPECS.map((s) => ({ s, score: s.keywords.reduce((n, k) => n + (has(k) ? k.length : 0), 0) })).filter((x) => x.score);
  const best = Math.max(0, ...scored.map((x) => x.score));
  // The best match, and close seconds (a "draggable bottom sheet" is a sheet and a drag release).
  return scored.filter((x) => x.score >= best * 0.6).sort((a, b) => b.score - a.score).slice(0, 3).map((x) => x.s);
}

export function formatMotionSpec(specs, { liveNames } = {}) {
  const kit = (names) => (liveNames ? names.filter((n) => liveNames.has(n)) : names);
  return specs
    .map((s) =>
      [
        `## ${s.title} (\`${s.id}\`) — ${s.register}`,
        '',
        `- Animate: ${s.animate}`,
        `- Enter: ${s.enter}`,
        `- Exit: ${s.exit}`,
        `- In JavaScript: ${s.js}`,
        `- Reduced motion: ${s.reduced}`,
        `- Avoid: ${s.avoid.join('; ')}`,
        ...(kit(s.kit).length ? [`- Already moves this way in the kit: ${kit(s.kit).join(', ')} (use it before writing the motion yourself)`] : []),
        ...(s.css ? ['', '```css', s.css, '```'] : []),
      ].join('\n'),
    )
    .concat([
      'Soft-motion rule: nothing starts or stops with a jolt, returns spring from where they are, every animation can be interrupted, the keyboard never waits for it. Play the interaction in a real browser (slow, fast flick, interrupted, keyboard, touch, reduced motion) before calling it smooth.',
    ])
    .join('\n\n');
}
